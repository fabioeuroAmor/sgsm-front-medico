// QA040 (F5), QA041 (voltar do navegador), QA042 (sessao expirada)
import fs from 'node:fs'
import * as L from './lib.mjs'
const contas = JSON.parse(fs.readFileSync(new URL('./contas.json', import.meta.url)))
const browser = await L.launch()
const A = await L.newSession(browser, 'SEC-A')
const B = await L.newSession(browser, 'SEC-B')
const pa = A.page, pb = B.page
const isReservaPost = (r) => r.url().endsWith('/agendamentos/reservas') && r.request().method() === 'POST'

await L.login(pa, contas.A.email, contas.A.senha)
await L.login(pb, contas.B.email, contas.B.senha)
await L.irAgendamentos(pa)

// QA040
L.start('QA040')
await L.wizardAte4(pa)
let w = pa.waitForResponse(isReservaPost)
await L.slotBtn(pa, '08:00').click()
const r40 = await w
L.note('POST 08:00 -> ' + r40.status() + ' ' + (await r40.text()))
await L.faixaReserva(pa).waitFor()
await L.shot(pa, 'QA040-a-reservado')
await pa.keyboard.press('F5')
await pa.waitForEvent('load', { timeout: 8000 }).then(() => L.note('recarregou via tecla F5')).catch(async () => { L.note('tecla F5 nao recarregou via CDP; usando page.reload() (equivalente ao F5)'); await pa.reload() })
await pa.getByRole('button', { name: 'Novo Agendamento' }).waitFor({ timeout: 20000 })
L.note('apos recarregar: url=' + pa.url())
await L.shot(pa, 'QA040-b-recarregado')
await L.wizardAte4(pa)
const gA = await L.gradeHorarios(pa)
L.note('grade SEC-A ao refazer o wizard: ' + JSON.stringify(gA) + ' | contem 08:00? ' + gA.includes('08:00') + ' | title do 08:00=' + await L.slotBtn(pa, '08:00').getAttribute('title').catch(() => null))
await L.shot(pa, 'QA040-c-SEC-A-grade')
await L.irAgendamentos(pb)
await L.wizardAte4(pb)
const gB = await L.gradeHorarios(pb)
L.note('grade SEC-B: ' + JSON.stringify(gB) + ' | contem 08:00? ' + gB.includes('08:00'))
await L.shot(pb, 'QA040-d-SEC-B-grade')
await L.fecharModal(pb)
await L.fecharModal(pa)
await L.end('QA040', 'a reserva de 08:00 fica orfa (a recarga nao executa limpeza) e expira em 10 min')

// QA041 — voltar do navegador
L.start('QA041')
await pa.getByRole('link', { name: 'Pacientes' }).first().click()
await pa.waitForURL('**/pacientes')
await L.irAgendamentos(pa)
await L.wizardAte4(pa)
w = pa.waitForResponse(isReservaPost)
await L.slotBtn(pa, '08:30').click()
L.note('POST 08:30 -> ' + (await w).status())
await L.faixaReserva(pa).waitFor()
await L.shot(pa, 'QA041-a-reservado')
const del = pa.waitForResponse((r) => r.request().method() === 'DELETE' && r.url().includes('/reservas/'), { timeout: 10000 }).catch(() => null)
await pa.goBack()
const d = await del
L.note('apos voltar: url=' + pa.url() + ' | DELETE: ' + (d ? `${d.url()} -> ${d.status()}` : 'NAO DISPARADO'))
await L.sleep(1500)
await L.shot(pa, 'QA041-b-voltou')
await L.end('QA041')

// QA042 — sessao expirada
L.start('QA042')
await L.irAgendamentos(pa)
await L.wizardAte4(pa)
await L.shot(pa, 'QA042-a-passo4')
await pa.evaluate(async () => {
  const m = await import('/src/services/tokenStore.ts')
  m.tokenStore.clear()
  localStorage.removeItem('refresh_token')
})
L.note('token de acesso (tokenStore em memoria) e refresh_token (localStorage) removidos via page.evaluate')
await L.slotBtn(pa, '09:00').click()
await pa.waitForURL('**/login', { timeout: 15000 }).then(() => L.note('redirecionado para /login')).catch(() => L.note('NAO redirecionou; url=' + pa.url()))
await L.sleep(1500)
L.note('texto visivel com "sess": ' + JSON.stringify(await pa.getByText(/sess[aã]o/i).allTextContents()) + ' | toasts=' + JSON.stringify(await pa.locator('[data-sonner-toast]').allTextContents()))
await L.shot(pa, 'QA042-b-login')
await L.end('QA042')
L.saveAll('g4b')
await browser.close()
