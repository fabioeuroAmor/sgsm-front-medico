// RODADA 2 — QA064 (preparacao): nao ha domiciliar de medico fora da Sao Lucas; o DEV cria pela UI um medico de QA
// SEM vinculo, com servico domiciliar e agenda domiciliar (quinta 08:00-10:00), e agenda um domiciliar para Zilma em 22/10 08:00
import fs from 'node:fs'
import * as L from './lib.mjs'
const R2 = new URL('./contas-r2.json', import.meta.url)
const r2 = JSON.parse(fs.readFileSync(R2))
const stamp = Date.now()
const NOME = 'QA Medico Fora'
const browser = await L.launch()
const dev = await L.newSession(browser, 'DEV')
const p = dev.page
await L.login(p, 'dev-local@sgsm.local', 'Dev088c00c5ba89!Aa')
L.start('QA064-r2-setup')
await p.getByRole('link', { name: 'Médicos' }).first().click()
await p.waitForURL('**/medicos')
await p.getByRole('button', { name: 'Novo Médico' }).click()
let m = L.modal(p)
await m.getByLabel('Nome completo').fill(NOME)
await m.getByLabel('CRM', { exact: true }).fill(String(stamp + 41).slice(-6))
await m.getByLabel('Especialidade').selectOption('Cardiologia')
await m.getByLabel('E-mail').fill(`qa.conflito.med.fora.${stamp}@teste.com`)
let w = p.waitForResponse((r) => r.url().endsWith('/v1/api/medicos') && r.request().method() === 'POST')
await m.getByRole('button', { name: 'Salvar' }).click()
let r = await w
const med = await r.json()
L.note(`POST /medicos -> ${r.status()} id=${med.id} (sem vinculo com estabelecimento)`)
r2.medicoFora = { id: med.id, nome: NOME }
fs.writeFileSync(R2, JSON.stringify(r2, null, 2))
await L.sleep(1500)

await p.getByRole('link', { name: 'Serviços' }).first().click()
await p.waitForURL('**/servicos')
await p.getByRole('button', { name: 'Novo Serviço' }).click()
m = L.modal(p)
await m.getByLabel('Médico').selectOption({ label: `${NOME} — Cardiologia` })
await m.getByLabel('Nome do Serviço').fill('QA Domiciliar Fora')
await m.getByLabel('Preço (R$)').fill('100')
await m.getByLabel('Duração (min)').fill('30')
await m.locator('label').filter({ hasText: 'Atendimento domiciliar' }).locator('div').first().click()
await m.getByLabel('Taxa de deslocamento (R$)').fill('10')
w = p.waitForResponse((r) => r.url().includes('/servicos-medicos') && r.request().method() === 'POST')
await m.getByRole('button', { name: 'Salvar' }).click()
r = await w
const serv = await r.json().catch(() => ({}))
L.note(`POST servicos-medicos -> ${r.status()} id=${serv.id} body=${r.request().postData()}`)
r2.medicoFora.servicoId = serv.id
fs.writeFileSync(R2, JSON.stringify(r2, null, 2))
await L.sleep(1500)

await p.getByRole('link', { name: 'Médicos' }).first().click()
await p.waitForURL('**/medicos')
await p.getByPlaceholder('Buscar por nome, CRM ou e-mail…').fill(NOME)
await L.sleep(1500)
await p.locator('div.grid > div').filter({ hasText: NOME }).first().getByTitle('Gerenciar agenda').click()
m = L.modal(p)
await m.getByRole('button', { name: /Adicionar Horário/ }).click()
await m.locator('label').filter({ hasText: 'Atendimento domiciliar' }).locator('div').first().click()
await m.getByLabel('Cidade').fill('Brasília')
await m.getByLabel('UF', { exact: true }).fill('DF')
await m.getByLabel('Raio (km)').fill('30')
await m.getByLabel('Dia da semana').selectOption('QUINTA')
await m.getByLabel('Duração do slot').selectOption('30')
await m.getByLabel('Hora início').fill('08:00')
await m.getByLabel('Hora fim').fill('10:00')
w = p.waitForResponse((r) => r.url().includes('/agenda-medico') && r.request().method() === 'POST')
await m.getByRole('button', { name: 'Salvar Horário' }).click()
r = await w
L.note(`POST agenda-medico -> ${r.status()} body=${r.request().postData()}`)
await L.sleep(1000)
await L.shot(p, 'QA064-r2-c-agenda-fora')
await m.locator('xpath=.//h2/following-sibling::button').click().catch(() => {})
await L.sleep(800)

// DEV agenda o domiciliar pelo wizard
await L.irAgendamentos(p)
await L.abrirWizard(p)
await L.passo1(p)
m = L.modal(p)
await m.getByPlaceholder('Buscar por serviço, médico ou especialidade…').fill('QA Domiciliar Fora')
await m.getByRole('button').filter({ hasText: 'QA Domiciliar Fora' }).first().click()
await m.getByRole('button', { name: 'Próximo', exact: true }).click()
await p.getByText('Passo 3 / 5').waitFor()
await L.passo3(p, 'Domiciliar')
await L.escolherDia(p, '22')
await L.esperarGrade(p)
L.note('grade 22/10 (QA Medico Fora): ' + JSON.stringify(await L.gradeHorarios(p)))
w = p.waitForResponse((r) => r.url().endsWith('/agendamentos/reservas') && r.request().method() === 'POST')
await L.slotBtn(p, '08:00').click()
r = await w
L.note(`POST reservas -> ${r.status()} ${await r.text()}`)
await L.modal(p).getByRole('button', { name: 'Próximo', exact: true }).click()
await p.getByText('Passo 5 / 5').waitFor()
w = p.waitForResponse((r) => r.url().endsWith('/v1/api/agendamentos') && r.request().method() === 'POST')
await L.modal(p).getByRole('button', { name: /Confirmar/ }).click()
r = await w
const ag = await r.json().catch(() => ({}))
L.note(`POST agendamentos -> ${r.status()} id=${ag.id} tipo=${ag.tipo} medico=${ag.medicoNome}`)
r2.medicoFora.agendamentoId = ag.id
fs.writeFileSync(R2, JSON.stringify(r2, null, 2))
await L.sleep(2500)
await L.shot(p, 'QA064-r2-d-DEV-criou-domiciliar-fora')
await L.end('QA064-r2-setup')
L.saveAll('r2-e')
await browser.close()
